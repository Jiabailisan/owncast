func sharedTestTranscoder(t *testing.T) *Transcoder {
	t.Helper()
	tr := newGoldenTranscoder()
	tr.codec = &NvencCodec{}
	tr.SetRTPOutputs([]RTPOutput{
		rtpTestOutput("h264_nvenc"),
		rtpTestOutput("h264_nvenc"),
	})
	return tr
}

func TestSharedTeeOutputEncodesTranscodeOnce(t *testing.T) {
	tr := sharedTestTranscoder(t)
	flags := tr.getFlags().command
	joined := strings.Join(flags, " ")

	if !tr.sharedOutputEnabled() {
		t.Fatal("expected shared tee output to be enabled")
	}
	if strings.Count(joined, "-f tee") != 1 {
		t.Fatalf("expected one tee output: %s", joined)
	}
	if got := strings.Count(joined, "-c:a:1 libopus"); got != 1 {
		t.Fatalf("expected one shared Opus encoder scoped to the extra audio stream, got %d: %s", got, joined)
	}
	if got := strings.Count(joined, "-c:v:0 h264_nvenc"); got != 1 {
		t.Fatalf("expected one transcode video encoder, got %d: %s", got, joined)
	}
	if strings.Contains(joined, "-master_pl_name") {
		t.Fatalf("master playlist is generated by Owncast in shared mode: %s", joined)
	}
	if !strings.Contains(joined, "-profile:v:0 main") {
		t.Fatalf("shared encode must use a browser-supported H.264 profile: %s", joined)
	}
	if !strings.Contains(joined, "bframes=0") && !strings.Contains(joined, "-bf:v:0 0") {
		t.Fatalf("shared encode must disable B-frames for WebRTC: %s", joined)
	}
	for _, want := range []string{"/0/stream.m3u8", "/0/stream-goldenid-", "rtp://127.0.0.1:40000", "rtp://127.0.0.1:40001"} {
		if !strings.Contains(joined, want) {
			t.Fatalf("shared output missing %q: %s", want, joined)
		}
	}
}

// TestSharedOpusOptionsUseAudioRelativeSpecifiers guards the stream specifier of the
// shared Opus encoder options.
//
// The Opus stream is an extra output audio stream, so its index is audio-relative.
// Addressing it with the flat output index (":N") points at a video stream as soon
// as there is more than one variant, and FFmpeg then drops the option with "Codec
// AVOption ... has not been used for any stream" - silently disabling the low-delay
// and frame-size settings WebRTC depends on.
func TestSharedOpusOptionsUseAudioRelativeSpecifiers(t *testing.T) {
	tr := sharedTestTranscoder(t)
	joined := strings.Join(tr.getFlags().command, " ")

	audioIndex := strconv.Itoa(len(tr.variants))
	for _, option := range []string{"-application", "-frame_duration", "-ar", "-ac"} {
		if !strings.Contains(joined, option+":a:"+audioIndex+" ") {
			t.Fatalf("expected %q to be scoped to the audio stream: %s", option+":a:"+audioIndex, joined)
		}
		if strings.Contains(joined, option+":"+audioIndex+" ") {
			t.Fatalf("%q uses the flat output index, which addresses a video stream: %s", option+":"+audioIndex, joined)
		}
	}
}

func TestSharedOutputFallsBackWhenAudioSettingsDiffer(t *testing.T) {
	tr := newGoldenTranscoder()
	tr.codec = &NvencCodec{}
	first := rtpTestOutput("h264_nvenc")
	second := rtpTestOutput("h264_nvenc")
	second.AudioURL = "rtp://127.0.0.1:40003?pkt_size=1200"
	second.OpusBitrateKbps = 64
	tr.SetRTPOutputs([]RTPOutput{first, second})

	if tr.sharedOutputEnabled() {
		t.Fatal("mismatched Opus settings must keep the legacy layout")
	}
	joined := strings.Join(tr.getFlags().command, " ")
	if strings.Contains(joined, "-f tee") {
		t.Fatalf("legacy fallback must not use tee: %s", joined)
	}
}

func TestSharedMasterPlaylistListsVariants(t *testing.T) {
	original := config.HLSStoragePath
	config.HLSStoragePath = filepath.Join(t.TempDir(), "hls")
	t.Cleanup(func() { config.HLSStoragePath = original })
	if err := os.MkdirAll(config.HLSStoragePath, 0o750); err != nil {
		t.Fatal(err)
	}

	tr := sharedTestTranscoder(t)
	tr.writeMasterPlaylist()

	data, err := os.ReadFile(filepath.Join(config.HLSStoragePath, "stream.m3u8"))
	if err != nil {
		t.Fatal(err)
	}
	master := string(data)
	if !strings.Contains(master, "#EXT-X-STREAM-INF:") || !strings.Contains(master, "0/stream.m3u8") {
		t.Fatalf("unexpected master playlist: %s", master)
	}
}

func TestSharedLegsSelectCompatibleHLSVariant(t *testing.T) {
	tr := new(Transcoder)
	tr.cfg = &config.Config{LogDirectory: "data/logs"}
	tr.ffmpegPath = "ffmpeg"
	tr.internalListenerPort = "8927"
	tr.input = "pipe:0"
	tr.inputFormat = ingest.FLVInputFormat()
	tr.currentLatencyLevel = models.GetLatencyLevel(2)
	tr.codec = &NvencCodec{}
	tr.SetIdentifier("goldenid")
	tr.AddVariant(HLSVariant{index: 0, isVideoPassthrough: true, isAudioPassthrough: true, cpuUsageLevel: 2})
	tr.AddVariant(HLSVariant{videoBitrate: 6000, isAudioPassthrough: true, cpuUsageLevel: 2})
	leg := rtpTestOutput("h264_nvenc")
	leg.VariantIndex = 0
	leg.H264Profile = "main"
	leg2 := rtpTestOutput("h264_nvenc")
	leg2.VariantIndex = 1
	leg2.VideoURL = "rtp://127.0.0.1:41000?pkt_size=1200"
	leg2.AudioURL = "rtp://127.0.0.1:41001?pkt_size=1200"
	tr.SetRTPOutputs([]RTPOutput{leg, leg2})
	if !tr.sharedOutputEnabled() {
		t.Fatal("expected shared output")
	}
	joined := strings.Join(tr.getSharedOutputFlags("http://127.0.0.1:8927"), " ")
	// WebRTC leg 0 is a transcode leg while HLS variant 0 is passthrough, so it
	// must select the transcode variant (v:1), never the source copy stream.
	if !strings.Contains(joined, "select=\\'v:1\\'") {
		t.Fatalf("transcode leg did not select the encoded HLS variant: %s", joined)
	}
}
